import { env } from "node:process";

/** Origin is an operator-controlled runtime setting, never a request header. */
export function internalApiOrigin(value: string | undefined = env.PLANE_INTERNAL_API_ORIGIN): string | null {
  if (!value) return null;
  try {
    const url = new URL(value);
    if (
      !["http:", "https:"].includes(url.protocol) ||
      url.username ||
      url.password ||
      url.pathname !== "/" ||
      url.search ||
      url.hash
    )
      return null;
    return url.origin;
  } catch {
    return null;
  }
}
